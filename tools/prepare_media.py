"""Build the FreeDOS floppy, display font, and optional legacy test media."""
import argparse
import base64
import hashlib
from pathlib import Path
import re
import shutil
import struct
import subprocess
import tempfile
from urllib.request import urlopen
from zipfile import ZipFile

from vga_clip import demo_frames, write_clip

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "glabios.rom": (
        "https://github.com/640-KB/GLaBIOS/releases/download/v0.4.2/GLABIOS_0.4.2_8X.ROM",
        "c2bc9ec1893c0ea4098433c862b97e546c4877c6a21c5bc23792ea2b6639c7d4",
    ),
    "font_8x8.c": (
        "https://cdn.jsdelivr.net/gh/torvalds/linux@v6.12/lib/fonts/font_8x8.c",
        "dc44051e83ae20b2b28aabcc6709897bffa15da9a6d4a39d875ac23dd11b587d",
    ),
    "FD14-FloppyEdition.zip": (
        "https://www.ibiblio.org/pub/micro/pc-stuff/freedos/files/distributions/1.4/FD14-FloppyEdition.zip",
        "45b1fa7c52dd996c3bfa5e352ffcd410781b952a6ad629f15a4c9ec4bbaefc5a",
    ),
}


def fetch(cache, name, sources=SOURCES):
    url, digest = sources[name]
    path = cache / name
    if not path.exists():
        with urlopen(url, timeout=60) as response:
            content = response.read()
        if hashlib.sha256(content).hexdigest() != digest:
            raise ValueError(f"Checksum mismatch for {name}")
        path.write_bytes(content)
    if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
        raise ValueError(f"Checksum mismatch for cached {path}")
    return path


def run(*args):
    subprocess.run(args, check=True)


def assemble(source, output, temporary):
    obj = temporary / "guest.o"
    run("as", "--32", "-I", ROOT / "guest", ROOT / "guest" / source, "-o", obj)
    run("objcopy", "-j", ".text", "-O", "binary", obj, output)


def unpack_dos_system(archive, source, target):
    with ZipFile(archive) as release:
        source.write_bytes(release.read("720k/x86BOOT.img"))
    run("mcopy", "-i", source, "::/KERNEL.SYS", target / "KERNEL.SYS")
    run("mcopy", "-i", source, "::/FREEDOS/BIN/COMMAND.COM", target / "COMMAND.COM")


def make_floppy(archive, directory):
    source = directory / "freedos720.img"
    unpack_dos_system(archive, source, directory)
    disk = directory / "freedos360.img"
    run("mformat", "-i", disk, "-f", "360", "-C", "-v", "LUAUXT", "::")
    with source.open("rb") as boot, disk.open("r+b") as target:
        original = boot.read(512)
        formatted = target.read(512)
        # Both use FAT12. Keep the 360 KiB BPB and copy the FreeDOS boot code.
        assert original[:3] == b"\xeb\x3c\x90" and original[-2:] == b"\x55\xaa"
        target.seek(0)
        target.write(original[:11] + formatted[11:62] + original[62:])
    assemble("hello.s", directory / "HELLO.COM", directory)
    assemble("cpu386.s", directory / "CPU386.COM", directory)
    assemble("pm386.s", directory / "PM386.COM", directory)
    startup = directory / "AUTOEXEC.BAT"
    startup.write_bytes(b"@ECHO OFF\r\nPROMPT $P$G\r\n")
    for name in ("KERNEL.SYS", "COMMAND.COM", "HELLO.COM", "CPU386.COM", "PM386.COM", "AUTOEXEC.BAT"):
        run("mcopy", "-i", disk, directory / name, f"::/{name}")
    return disk.read_bytes()


def module(path, image):
    # Omit empty sectors and limit each base64 string to 12 KiB.
    entries = []
    start = 0
    data = bytearray()
    for offset in range(0, len(image), 512):
        sector = image[offset:offset + 512]
        if not any(sector) or len(data) >= 9 * 1024:
            if data:
                entries.append((start, base64.b64encode(data).decode("ascii")))
                data.clear()
            if not any(sector):
                continue
        if not data:
            start = offset
        data.extend(sector)
    if data:
        entries.append((start, base64.b64encode(data).decode("ascii")))
    lines = ["-- Generated by tools/prepare_media.py.", "return {", f"\tsize = {len(image)},", "\tchunks = {"]
    lines.extend(f'\t\t{{ {offset}, "{encoded}" }},' for offset, encoded in entries)
    lines.extend(["\t},", "}", ""])
    content = "\n".join(lines)
    if len(content) >= 200_000:
        raise ValueError(f"{path.name} is too large for a Roblox ModuleScript")
    path.write_text(content, encoding="ascii")


def disk_modules(folder, image):
    folder.mkdir(parents=True, exist_ok=True)
    block_size = 96 * 1024
    parts = []
    for offset in range(0, len(image), block_size):
        block = image[offset : offset + block_size]
        if any(block):
            name = f"Part{len(parts):03}"
            module(folder / f"{name}.luau", block)
            parts.append((offset, name))
    index = ["-- Generated by tools/prepare_media.py.", f"return {{ size = {len(image)}, parts = {{"]
    index.extend(f'\t{{ {offset}, "{name}" }},' for offset, name in parts)
    index.extend(["} }", ""])
    (folder / "Index.luau").write_text("\n".join(index), encoding="ascii")
    for old in folder.glob("Part[0-9][0-9][0-9].luau"):
        if int(old.stem[4:]) >= len(parts):
            old.unlink()


def sample_bmp():
    # Uneven placement and padded scanlines exercise the DOS viewer's row handling.
    width, height = 318, 196
    stride = (width + 3) & ~3
    palette = bytearray()
    for index in range(256):
        red = (index >> 5) * 255 // 7
        green = ((index >> 2) & 7) * 255 // 7
        blue = (index & 3) * 255 // 3
        palette.extend((blue, green, red, 0))
    pixels = bytearray(stride * height)
    bars = (255, 252, 31, 28, 227, 224, 3, 0)
    for y in range(height):
        row = (height - 1 - y) * stride
        for x in range(width):
            pixels[row + x] = bars[x * 8 // width] if y < 128 else x * 256 // width
        pixels[row + width:row + stride] = bytes([255]) * (stride - width)
    pixel_offset = 54 + len(palette)
    file_header = struct.pack("<2sIHHI", b"BM", pixel_offset + len(pixels), 0, 0, pixel_offset)
    bitmap_info = struct.pack("<IiiHHIIiiII", 40, width, height, 1, 8, 0, len(pixels), 0, 0, 256, 0)
    return file_header + bitmap_info + palette + pixels


def write_vga_programs(target, temporary):
    assemble("bmpview.s", target / "BMPVIEW.COM", temporary)
    (target / "SAMPLE.BMP").write_bytes(sample_bmp())
    assemble("vgaclip.s", target / "VGACLIP.COM", temporary)
    with (target / "DEMO.VCL").open("wb") as demo:
        write_clip(demo, demo_frames())


def make_vga_floppy(floppy, directory):
    disk = directory / "vga-floppy.img"
    disk.write_bytes(floppy)
    write_vga_programs(directory, directory)
    for name in ("BMPVIEW.COM", "SAMPLE.BMP", "VGACLIP.COM", "DEMO.VCL"):
        run("mcopy", "-i", disk, directory / name, f"::/{name}")
    return disk.read_bytes()


def option_rom(source, directory):
    output = directory / "option-rom.bin"
    assemble(source, output, directory)
    image = bytearray(output.read_bytes())
    if image[:2] != b"\x55\xaa" or len(image) != image[2] * 512:
        raise ValueError(f"Invalid option ROM {source}")
    image[-1] = -sum(image[:-1]) % 256
    return image


def system_bios(bios, directory):
    # Redirect only the CPU row's string-printer call. Keep the original ROM
    # at F000:E000 and map a small firmware extension immediately before it.
    call_offset = 0x16DE
    call_site = bytes.fromhex("f6 06 12 00 04 74 03 be 27 e5 e8 bd 00 e8 9f 00")
    if len(bios) != 8192 or bios[call_offset - 10:call_offset + 6] != call_site:
        raise ValueError("Unexpected GLaBIOS POST code")
    patched = bytearray(bios)
    struct.pack_into("<h", patched, call_offset + 1, 0xDE00 - (0xE000 + call_offset + 3))
    patched[-1] = -sum(patched[:-1]) % 256
    hook = directory / "post-cpu.bin"
    assemble("post-cpu.s", hook, directory)
    return hook.read_bytes() + patched


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=ROOT / ".boot_media")
    parser.add_argument("--output", type=Path, default=ROOT / "src/media")
    parser.add_argument("--legacy", action="store_true", help="Also generate GLaBIOS fixtures for the legacy tests")
    args = parser.parse_args()
    for tool in ("as", "objcopy", "mformat", "mcopy"):
        if shutil.which(tool) is None:
            parser.error(f"Install {tool} first (GNU binutils and mtools are required)")
    args.cache.mkdir(parents=True, exist_ok=True)
    args.output.mkdir(parents=True, exist_ok=True)
    release = fetch(args.cache, "FD14-FloppyEdition.zip")
    font_source = fetch(args.cache, "font_8x8.c").read_text(encoding="utf-8")
    font = bytes(int(value, 16) for value in re.findall(r"^\s*0x([0-9a-f]{2}),", font_source, re.M))
    if len(font) != 256 * 8:
        raise ValueError("Expected 256 eight-row glyphs")
    with tempfile.TemporaryDirectory(prefix="luau-xt-") as temporary:
        directory = Path(temporary)
        disk = make_floppy(release, directory)
        vga_disk = make_vga_floppy(disk, directory)
        if args.legacy:
            bios = fetch(args.cache, "glabios.rom").read_bytes()
            module(args.output / "Bios.luau", system_bios(bios, directory))
            module(args.output / "AtBios.luau", option_rom("at-bios-rom.s", directory))
            module(args.output / "VgaBios.luau", option_rom("vga-bios.s", directory))
            module(args.output / "Disk.luau", disk)
            boot = directory / "boot-test.bin"
            assemble("boot-test.s", boot, directory)
            module(args.output / "BootTest.luau", boot.read_bytes().ljust(len(disk), b"\0"))
    module(args.output / "Font.luau", font)
    disk_modules(args.output / "vga_disk", vga_disk)


if __name__ == "__main__":
    main()
